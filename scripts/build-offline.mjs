import fs from 'node:fs/promises';
import path from 'node:path';
import { build } from 'vite';

const projectRoot = process.cwd();
const buildDir = path.join(projectRoot, '.offline-build');
const outputFile = path.join(projectRoot, 'index.html');

async function toDataUri(relativePath, mimeType) {
  const content = await fs.readFile(path.join(projectRoot, relativePath));
  return `data:${mimeType};base64,${content.toString('base64')}`;
}

function escapeScript(content) {
  return content.replace(/<\/script/gi, '<\\/script');
}

function escapeStyle(content) {
  return content.replace(/<\/style/gi, '<\\/style');
}

await build({ configFile: path.join(projectRoot, 'vite.offline.config.js') });

let html = await fs.readFile(path.join(buildDir, 'index.dev.html'), 'utf8');

const scriptTagPattern = /<script\b[^>]*\bsrc="([^"]+\.js)"[^>]*>\s*<\/script>/i;
const scriptTag = html.match(scriptTagPattern);
if (!scriptTag) {
  throw new Error('Offline build did not produce a JavaScript bundle.');
}

const scriptPath = path.join(buildDir, scriptTag[1].replace(/^\.\//, ''));
const scriptContent = await fs.readFile(scriptPath, 'utf8');
const inlineScript = `<script>\n${escapeScript(scriptContent)}\n</script>`;
html = html.replace(scriptTag[0], '');
html = html.replace('</body>', `${inlineScript}\n  </body>`);

const stylesheetPattern = /<link\b[^>]*\brel="stylesheet"[^>]*\bhref="([^"]+\.css)"[^>]*>/gi;
const stylesheetTags = [...html.matchAll(stylesheetPattern)];
if (stylesheetTags.length === 0) {
  throw new Error('Offline build did not produce a CSS bundle.');
}

for (const tag of stylesheetTags) {
  const cssPath = path.join(buildDir, tag[1].replace(/^\.\//, ''));
  const cssContent = await fs.readFile(cssPath, 'utf8');
  html = html.replace(tag[0], () => `<style>\n${escapeStyle(cssContent)}\n</style>`);
}

html = html.replace(/<link\b[^>]*\brel="(?:modulepreload|preload)"[^>]*>/gi, '');

const logoUri = await toDataUri('public/assets/divya_logo.svg', 'image/svg+xml');
const illustrationUri = await toDataUri('public/assets/learning_dashboard_illustration.webp', 'image/webp');
const faviconUri = await toDataUri('public/favicon.svg', 'image/svg+xml');

const assetReplacements = [
  [/(?:\.\/|\/)assets\/divya_logo\.svg/g, logoUri],
  [/(?:\.\/|\/)assets\/learning_dashboard_illustration\.webp/g, illustrationUri],
  [/(?:\.\/|\/)favicon\.svg/g, faviconUri],
];

for (const [pattern, dataUri] of assetReplacements) {
  html = html.replace(pattern, () => dataUri);
}

html = html.replace(
  /<!doctype html>/i,
  '<!doctype html>\n<!-- Generated by npm run build:offline. Edit index.dev.html and src/ instead. -->',
);

const checks = [
  ['external script', /<script\b[^>]*\bsrc=/i],
  ['external stylesheet', /<link\b[^>]*\brel="stylesheet"/i],
  ['external image', /<img\b[^>]*\bsrc="https?:/i],
  ['uninlined asset path', /(?:\/|\.\/)assets\//i],
  ['uninlined favicon', /(?:\/|\.\/)favicon\.svg/i],
];

for (const [label, pattern] of checks) {
  if (pattern.test(html)) {
    throw new Error(`Offline HTML still contains an ${label}.`);
  }
}

await fs.writeFile(outputFile, html, 'utf8');
await fs.rm(buildDir, { recursive: true, force: true });

console.log(`Generated ${path.relative(projectRoot, outputFile)} (${(Buffer.byteLength(html) / 1024).toFixed(1)} KB).`);
